import SwiftUI
import UIKit

/// AI summary sheet of the reader — Editorial Teal (design canvas ·
/// "17 · Riassunto AI"): sparkle header with "Summary" and the reading-time
/// saving, the summary as readable Markdown (`SummaryMarkdownView`) with no
/// card around it, length / format options, Copy · Share · Generate actions
/// and the AI disclaimer.
struct AISummaryView: View {
    let article: Article
    let fontFamily: Typography.FontFamily
    let onGenerate: (String, String) -> Void // Passes length and format
    let isGenerating: Bool
    let error: String?

    @EnvironmentObject var themeManager: ThemeManager
    @Environment(\.dismiss) private var dismiss

    @State private var selectedLength: SummaryLength = .medium
    @State private var selectedFormat: SummaryFormat = .summary
    @State private var didCopy = false
    /// Remembered between openings
    @AppStorage("aiSummaryFontSize") private var fontSize: Double = 17

    private let minFontSize: Double = 14
    private let maxFontSize: Double = 26

    private var summary: String? {
        guard let text = article.aiSummary, !text.isEmpty else { return nil }
        return text
    }

    var body: some View {
        VStack(spacing: 0) {
            header

            ScrollView {
                VStack(alignment: .leading, spacing: 20) {
                    if let summary {
                        SummaryMarkdownView(
                            markdown: summary,
                            fontFamily: fontFamily,
                            fontSize: CGFloat(fontSize),
                            colors: themeManager.colors
                        )
                        .opacity(isGenerating ? 0.5 : 1)
                    } else if !isGenerating {
                        emptyState
                    }

                    if isGenerating {
                        HStack(spacing: 10) {
                            ProgressView()
                                .tint(themeManager.colors.accent)
                            Text("Generating summary…")
                                .font(Typography.ui(14, weight: .semibold, relativeTo: .subheadline))
                                .foregroundColor(themeManager.colors.muted)
                        }
                        .frame(maxWidth: .infinity)
                        .padding(.vertical, 8)
                    }

                    if let error {
                        Label(error, systemImage: "exclamationmark.triangle")
                            .font(Typography.ui(13, relativeTo: .footnote))
                            .foregroundColor(themeManager.colors.accent800)
                            .padding(12)
                            .frame(maxWidth: .infinity, alignment: .leading)
                            .background(themeManager.colors.accent200)
                            .clipShape(RoundedRectangle(cornerRadius: 14, style: .continuous))
                    }

                    options

                    actions

                    Text("Generated by AI (Cohere) from the saved article. Check the original for details.")
                        .font(Typography.ui(12, relativeTo: .caption))
                        .foregroundColor(themeManager.colors.muted)
                        .multilineTextAlignment(.center)
                        .frame(maxWidth: .infinity)
                }
                .padding(.horizontal, 20)
                .padding(.top, 16)
                .padding(.bottom, 32)
            }
        }
        .background(themeManager.colors.page.ignoresSafeArea())
    }

    // MARK: - Header

    private var header: some View {
        VStack(spacing: 0) {
            Capsule()
                .fill(themeManager.colors.line)
                .frame(width: 36, height: 5)
                .padding(.top, 10)
                .accessibilityHidden(true)

            HStack(spacing: 10) {
                Image(systemName: "sparkles")
                    .font(Typography.symbol(17, weight: .semibold))
                    .foregroundColor(themeManager.colors.accent)
                    .frame(width: 36, height: 36)
                    .background(RoundedRectangle(cornerRadius: 10).fill(themeManager.colors.accent200))
                    .accessibilityHidden(true)

                VStack(alignment: .leading, spacing: 1) {
                    Text("Summary")
                        .font(Typography.ui(17, weight: .bold, relativeTo: .headline))
                        .foregroundColor(themeManager.colors.text)
                        .accessibilityAddTraits(.isHeader)
                    Text(subtitle)
                        .font(Typography.ui(12.5, relativeTo: .caption))
                        .foregroundColor(themeManager.colors.muted)
                        .lineLimit(1)
                }

                Spacer(minLength: 8)

                if summary != nil {
                    textSizeControl
                }

                Button(action: { dismiss() }) {
                    Image(systemName: "xmark")
                        .font(Typography.symbol(13, weight: .bold))
                        .foregroundColor(themeManager.colors.text)
                        .frame(width: 32, height: 32)
                        .background(Circle().fill(themeManager.colors.surface))
                }
                .buttonStyle(.plain)
                .minimumTapTarget()
                .accessibilityLabel("Close summary")
            }
            .padding(.horizontal, 20)
            .padding(.top, 6)
            .padding(.bottom, 8)

            Rectangle()
                .fill(themeManager.colors.line)
                .frame(height: 1)
        }
    }

    /// "9 min article · generated 18 Nov, 12:30" (or "· 1 min summary").
    private var subtitle: String {
        var parts: [String] = []
        if let minutes = article.estimatedReadTime, minutes > 0 {
            parts.append("\(minutes) min article")
        }
        if let generated = generatedLabel {
            parts.append(generated)
        } else if summary != nil {
            parts.append("1 min summary")
        }
        return parts.isEmpty ? article.title : parts.joined(separator: " · ")
    }

    private var textSizeControl: some View {
        HStack(spacing: 0) {
            Button(action: { fontSize = max(minFontSize, fontSize - 1.5) }) {
                Text("A")
                    .font(Typography.ui(12, weight: .semibold))
                    .frame(width: 32, height: 32)
                    .contentShape(Rectangle())
            }
            .disabled(fontSize <= minFontSize)
            .accessibilityLabel("Decrease text size")

            Rectangle().fill(themeManager.colors.line).frame(width: 1, height: 16)

            Button(action: { fontSize = min(maxFontSize, fontSize + 1.5) }) {
                Text("A")
                    .font(Typography.ui(17, weight: .semibold))
                    .frame(width: 32, height: 32)
                    .contentShape(Rectangle())
            }
            .disabled(fontSize >= maxFontSize)
            .accessibilityLabel("Increase text size")
        }
        .buttonStyle(.plain)
        .foregroundColor(themeManager.colors.text)
        .overlay(Capsule().stroke(themeManager.colors.line, lineWidth: 1))
    }

    // MARK: - Empty state

    private var emptyState: some View {
        VStack(spacing: 10) {
            Text("No summary yet")
                .font(Typography.ui(17, weight: .semibold, relativeTo: .headline))
                .foregroundColor(themeManager.colors.text)
            Text("Choose length and format, then tap Generate. The summary is kept with the article.")
                .font(Typography.ui(14, relativeTo: .subheadline))
                .foregroundColor(themeManager.colors.muted)
                .multilineTextAlignment(.center)
                .fixedSize(horizontal: false, vertical: true)
        }
        .frame(maxWidth: .infinity)
        .padding(.vertical, 28)
        .padding(.horizontal, 20)
        .background(themeManager.colors.surface)
        .clipShape(RoundedRectangle(cornerRadius: CornerRadius.card, style: .continuous))
    }

    // MARK: - Options

    private var options: some View {
        VStack(alignment: .leading, spacing: 12) {
            optionRow(title: "Length") {
                ForEach(SummaryLength.allCases) { length in
                    segment(length.label, isSelected: selectedLength == length) { selectedLength = length }
                }
            }

            optionRow(title: "Format") {
                ForEach(SummaryFormat.allCases) { format in
                    segment(format.label, isSelected: selectedFormat == format) { selectedFormat = format }
                }
            }
        }
        .disabled(isGenerating)
    }

    private func optionRow<Content: View>(title: String, @ViewBuilder content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 8) {
            Text(title)
                .font(Typography.ui(13, weight: .semibold, relativeTo: .footnote))
                .foregroundColor(themeManager.colors.accent2)

            HStack(spacing: 2) {
                content()
            }
            .padding(3)
            .background(themeManager.colors.surface)
            .clipShape(Capsule())
        }
    }

    private func segment(_ title: String, isSelected: Bool, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Text(title)
                .font(Typography.ui(13.5, weight: isSelected ? .semibold : .regular))
                .foregroundColor(isSelected ? themeManager.colors.text : themeManager.colors.muted)
                .frame(maxWidth: .infinity, minHeight: 34)
                .background(isSelected ? themeManager.colors.page : Color.clear)
                .clipShape(Capsule())
                .shadow(color: isSelected ? Color(hex: "#16191A").opacity(0.12) : .clear, radius: 1, x: 0, y: 1)
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(isSelected ? [.isSelected] : [])
    }

    // MARK: - Actions

    private var actions: some View {
        HStack(spacing: 8) {
            if let summary {
                Button {
                    UIPasteboard.general.string = summary
                    didCopy = true
                    Task {
                        try? await Task.sleep(nanoseconds: 1_500_000_000)
                        didCopy = false
                    }
                } label: {
                    outlinePill(didCopy ? "Copied" : "Copy", systemImage: didCopy ? "checkmark" : "doc.on.doc")
                }
                .buttonStyle(.plain)

                ShareLink(item: summary) {
                    outlinePill("Share", systemImage: "square.and.arrow.up")
                }
                .buttonStyle(.plain)
            }

            Button(action: { onGenerate(selectedLength.rawValue, selectedFormat.rawValue) }) {
                HStack(spacing: 6) {
                    if isGenerating {
                        ProgressView()
                            .tint(themeManager.colors.page)
                    } else {
                        Image(systemName: "sparkles")
                    }
                    Text(summary == nil ? "Generate" : "Regenerate")
                }
                .font(Typography.ui(14, weight: .semibold))
                .foregroundColor(themeManager.colors.page)
                .frame(maxWidth: .infinity, minHeight: 44)
                .background(Capsule().fill(themeManager.colors.accent))
                .opacity(isGenerating ? 0.7 : 1)
            }
            .buttonStyle(.plain)
            .disabled(isGenerating)
        }
    }

    private func outlinePill(_ title: String, systemImage: String) -> some View {
        HStack(spacing: 6) {
            Image(systemName: systemImage)
            Text(title)
        }
        .font(Typography.ui(14, weight: .semibold))
        .foregroundColor(themeManager.colors.text)
        .frame(maxWidth: .infinity, minHeight: 44)
        .overlay(Capsule().stroke(themeManager.colors.line, lineWidth: 1))
        .contentShape(Capsule())
    }

    // MARK: - Helpers

    private var generatedLabel: String? {
        guard let date = PublicLinkValidity.parseDate(article.aiSummaryGeneratedAt) else { return nil }
        return "generated \(date.formatted(date: .abbreviated, time: .shortened))"
    }
}

// MARK: - Options

enum SummaryLength: String, CaseIterable, Identifiable {
    case short, medium, long
    var id: String { rawValue }
    var label: String {
        switch self {
        case .short: return "Short"
        case .medium: return "Medium"
        case .long: return "Long"
        }
    }
}

enum SummaryFormat: String, CaseIterable, Identifiable {
    case summary
    case bullet
    var id: String { rawValue }
    var label: String {
        switch self {
        case .summary: return "Summary"
        case .bullet: return "Bullet points"
        }
    }
}
